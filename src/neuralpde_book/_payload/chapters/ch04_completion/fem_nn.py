"""Section 4.5.3: learn an unknown source through a classical P1 FEM solve.

The state is never a neural network. A sine-feature source network supplies the
load; sparse transpose solves implement its exact discrete reverse derivative.
Noisy/sparse identification and nonlinear coefficients are outside this example.

Book/code notation:
Book 4.5.3: a learned source f_theta feeds a classical P1 state solve. The sparse transpose solve supplies the derivative; state and source approximation errors are different quantities.
"""

import copy
import numpy as np
import torch
from scipy.optimize import minimize
from chapters.ch04.fem import Reference
from chapters.ch04.problem import Problem
from .common import ALPHA, DIM, LAM, SineHead, SpectralProblem, basis, tensor


class SparseSolve(torch.autograd.Function):
    @staticmethod
    def forward(ctx, load, fem):
        ctx.fem = fem
        fem.counts["state"] += 1
        return tensor(fem.ref.lu.solve(load.detach().numpy()))

    @staticmethod
    def backward(ctx, derivative):
        ctx.fem.counts["adjoint"] += 1
        return tensor(ctx.fem.ref.lu.solve(derivative.detach().numpy(), trans="T")), None


class SourceIdentification:
    def __init__(self, mesh=32):
        self.ref = Reference(Problem(), mesh, 4)
        self.counts = dict(state=0, adjoint=0)
        self.space = SpectralProblem()
        r = self.ref
        bq = basis(r.points)
        self.Bload = np.stack([r.load(bq[..., j])[r.interior] for j in range(DIM)], 1)
        self.G = np.einsum("eqi,eq,eqj->ij", bq, r.weights, bq)
        self.L = tensor(self.Bload * LAM[None, :])
        # Noise-free analytic observations at u=0, not observations generated by
        # this training FEM discretization. Validation uses a separate mesh.
        self.observed = tensor(basis(r.nodes[r.interior]) @ (self.space.f / LAM))
        self.observed_norm2 = float(self.observed.numpy() @ r.Mi @ self.observed.numpy())
        mi = r.Mi.tocoo()
        self.mass = torch.sparse_coo_tensor(
            np.stack([mi.row, mi.col]), mi.data, mi.shape, dtype=torch.float64
        ).coalesce()

    def state(self, theta):
        return SparseSolve.apply(self.L @ theta, self)

    def loss(self, theta, regularization=1e-12):
        e = self.state(theta) - self.observed
        me = torch.sparse.mm(self.mass, e[:, None])[:, 0]
        return 0.5 * (e @ me) / self.observed_norm2 + 0.5 * regularization * theta.square().sum()

    def relative_misfit(self, theta):
        with torch.no_grad():
            e = (self.state(theta) - self.observed).numpy()
        return float(np.sqrt((e @ self.ref.Mi @ e) / self.observed_norm2))

    def control(self, theta):
        """Freeze learned source, then optimize the same 17-mode control space."""
        source_load = self.L.numpy() @ theta
        r = self.ref
        ix = r.interior
        bq = basis(r.points)

        def fun(u):
            self.counts["state"] += 1
            self.counts["adjoint"] += 1
            y = r.lu.solve(source_load + self.Bload @ u)
            p = r.lu.solve(r.Mi @ y - r.ydl[ix], trans="T")
            objective = r.objective(r.at_quad(r.expand(y)), np.einsum("eqi,i->eq", bq, u))
            derivative = self.Bload.T @ p + ALPHA * self.G @ u
            return objective, derivative

        opt = minimize(
            fun, np.zeros(DIM), method="BFGS", jac=True, options=dict(gtol=1e-12, maxiter=300)
        )
        return opt.x, dict(
            success=bool(opt.success),
            message=str(opt.message),
            iterations=int(opt.nit),
            learned_model_objective=float(opt.fun),
        )


def run(mesh=32, validation_mesh=64, maxiter=150):
    if validation_mesh <= mesh or maxiter < 1:
        raise ValueError("require a finer independent validation mesh and positive budget")
    train, val = SourceIdentification(mesh), SourceIdentification(validation_mesh)
    network = SineHead()  # f_theta(x) = B(x) @ (lambda * theta)
    history, best, calls = [], None, 0
    optimizer = torch.optim.LBFGS(
        network.parameters(),
        lr=1.0,
        max_iter=1,
        tolerance_grad=1e-12,
        tolerance_change=1e-24,
        line_search_fn="strong_wolfe",
    )

    def record():
        nonlocal best
        v = val.relative_misfit(network.weight)
        t = train.relative_misfit(network.weight)
        history.append(
            dict(
                iteration=len(history),
                train_observation_relative_l2=t,
                validation_observation_relative_l2=v,
            )
        )
        if best is None or v < best["score"]:
            best = dict(score=v, theta=network.weight.detach().clone(), index=len(history) - 1)

    record()
    for _ in range(maxiter):

        def closure():
            nonlocal calls
            optimizer.zero_grad(set_to_none=True)
            loss = train.loss(network.weight)
            if not bool(torch.isfinite(loss)):
                raise FloatingPointError("nonfinite inverse loss")
            loss.backward()
            calls += 1
            return loss

        optimizer.step(closure)
        record()
        loss = train.loss(network.weight)
        (gradient,) = torch.autograd.grad(loss, network.weight)
        if float(gradient.abs().max()) < 1e-10:
            break
    theta = best["theta"].numpy()
    # Use the finer discretization for downstream control with fixed learned f.
    u, optimization = val.control(theta)
    space = SpectralProblem()
    delta_source = LAM * theta - space.f
    source_error = float(
        np.sqrt(delta_source @ space.gram @ delta_source) / np.sqrt(space.f @ space.gram @ space.f)
    )
    return dict(
        control=u,
        source_head=theta,
        best_index=best["index"],
        history=history,
        diagnostics=space.diagnostics(u),
        optimizer=optimization,
        learned_source_relative_l2=source_error,
        iterations=len(history) - 1,
        selected_validation_observation_relative_l2=best["score"],
        counts=dict(training=train.counts, validation_and_online=val.counts, closure_calls=calls),
        data=dict(
            training_nodes=train.ref.nodes[train.ref.interior],
            training_observations=train.observed.numpy(),
            validation_nodes=val.ref.nodes[val.ref.interior],
            validation_observations=val.observed.numpy(),
        ),
    )
